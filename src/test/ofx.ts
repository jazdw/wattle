/** A made-up download holding one account per number (the same statement under each), with extra transactions for some. */
export function sgmlAccounts(numbers: string[], extra: Record<string, string> = {}): string {
  const one = sgml(buy('B1', '20260803', '10', '12.5', '125.00'));
  const statement = one.slice(one.indexOf('<INVSTMTTRNRS>'), one.indexOf('</INVSTMTMSGSRSV1>'));
  const statements = numbers.map((number) => statement.replace('<ACCTID>12345678', `<ACCTID>${number}`).replace('</INVTRANLIST>', `${extra[number] ?? ''}</INVTRANLIST>`));
  return one.slice(0, one.indexOf('<INVSTMTTRNRS>')) + statements.join('') + one.slice(one.indexOf('</INVSTMTMSGSRSV1>'));
}
